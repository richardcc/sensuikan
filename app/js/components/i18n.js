function getSupportedLanguages() {
  return Object.keys(I18N).filter((key) => I18N[key] && typeof I18N[key] === 'object');
}

function getNextLanguage(lang) {
  const languages = getSupportedLanguages();
  const currentIndex = languages.indexOf(lang);
  return languages[(currentIndex + 1 + languages.length) % languages.length] || 'es';
}

function t(key, defaultVal) {
  const lang = window.currentLang || 'es';
  const dict = I18N[lang] || I18N['es'];
  const value = key.split('.').reduce((result, part) => result && result[part], dict);
  return value !== undefined ? value : (defaultVal !== undefined ? defaultVal : key);
}

const I18N_LETTER_REGEX = /[a-zA-Z\u00C0-\u024F\u1E00-\u1EFF]/;

function translateText(text, language) {
  const source = (text || '').trim();
  if (!source) return text;

  // Fast bailout: if string has no letters (numbers, symbols, dice emoji, punctuation), skip
  if (!I18N_LETTER_REGEX.test(source)) return text;

  const translators = getTextTranslators(language);
  if (Object.prototype.hasOwnProperty.call(translators.exact, source)) return translators.exact[source];
  if (translators.cache.has(source)) return translators.cache.get(source);

  // If short (< 3 chars) and not in exact dictionary, long phrases (len >= 5) cannot match inside
  if (source.length < 3) {
    translators.cache.set(source, source);
    return source;
  }

  let translated = translators.phrases.reduce(
    (value, [key, replacement]) => value.includes(key) ? value.replaceAll(key, replacement) : value,
    source
  );
  translators.words.forEach(({ pattern, replacement }) => {
    translated = translated.replace(pattern, `$1${replacement}`);
  });
  translators.cache.set(source, translated);
  return translated;
}

const TEXT_TRANSLATOR_CACHE = new Map();
function getTextTranslators(language) {
  const lang = TEXT_TRANSLATIONS_BY_LANGUAGE[language] ? language : 'es';
  if (TEXT_TRANSLATOR_CACHE.has(lang)) return TEXT_TRANSLATOR_CACHE.get(lang);

  const map = TEXT_TRANSLATIONS_BY_LANGUAGE[lang];
  const phrases = Object.keys(map)
    .filter((key) => key.length >= 5)
    .sort((a, b) => b.length - a.length)
    .map((key) => [key, map[key]]);
  const words = Object.entries(COMMON_TEXT_WORDS[lang] || {})
    .sort(([a], [b]) => b.length - a.length)
    .map(([word, replacement]) => ({
      pattern: new RegExp(`(^|[^\\p{L}])${word}(?=$|[^\\p{L}])`, 'giu'),
      replacement
    }));
  const translators = { exact: map, phrases, words, cache: new Map() };
  TEXT_TRANSLATOR_CACHE.set(lang, translators);
  return translators;
}

function applyTextTranslations(language, root) {
  const scope = root || (typeof document !== 'undefined' ? (document.body || document) : null);
  if (!scope) return;
  const doc = scope.ownerDocument || (typeof document !== 'undefined' ? document : null);

  // High-performance path: Native TreeWalker visits only leaf text nodes in a single flat pass,
  // bypassing script/style/svg/code and avoiding thousands of intermediate element array allocations.
  if (doc && typeof doc.createTreeWalker === 'function') {
    const walker = doc.createTreeWalker(
      scope,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode: function(node) {
          const parent = node.parentNode;
          if (!parent) return NodeFilter.FILTER_REJECT;
          const tag = parent.nodeName;
          if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'SVG' || tag === 'CODE' || tag === 'PRE' || tag === 'TEXTAREA') {
            return NodeFilter.FILTER_REJECT;
          }
          if (parent.closest && parent.closest('[data-i18n-managed="true"], #comp-sec2-ocr-container, .ocr-board-b1-b6, #comp-t4-tables-container, #comp-grid-t1, #comp-grid-t2, #comp-grid-t3, #comp-grid-t5')) {
            return NodeFilter.FILTER_REJECT;
          }
          return NodeFilter.FILTER_ACCEPT;
        }
      }
    );

    let node;
    while ((node = walker.nextNode())) {
      const original = node.textContent;
      const trimmed = original.trim();
      if (!trimmed) continue;
      const translated = translateText(trimmed, language);
      if (translated !== trimmed) {
        const start = original.indexOf(trimmed);
        node.textContent = `${original.slice(0, start)}${translated}${original.slice(start + trimmed.length)}`;
      }
    }
    return;
  }

  // Fallback for environments without TreeWalker
  const elements = scope.querySelectorAll('button, h1, h2, h3, h4, h5, th, td, label, div, span, p, caption, option, small, b, strong, i, em');
  elements.forEach((element) => {
    if (element.closest && element.closest('[data-i18n-managed="true"], #comp-sec2-ocr-container, .ocr-board-b1-b6, #comp-t4-tables-container, #comp-grid-t1, #comp-grid-t2, #comp-grid-t3, #comp-grid-t5')) return;
    Array.from(element.childNodes).forEach((node) => {
      if (node.nodeType !== Node.TEXT_NODE) return;
      const original = node.textContent;
      const trimmed = original.trim();
      if (!trimmed) return;
      const translated = translateText(trimmed, language);
      if (translated !== trimmed) {
        const start = original.indexOf(trimmed);
        node.textContent = `${original.slice(0, start)}${translated}${original.slice(start + trimmed.length)}`;
      }
    });
  });
}

function applyKeyedTranslations(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n, el.textContent);
  });
  scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml, el.innerHTML);
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder, el.getAttribute('placeholder') || ''));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.dataset.i18nTitle, el.getAttribute('title') || ''));
  });
  scope.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel, el.getAttribute('aria-label') || ''));
  });
  scope.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.setAttribute('alt', t(el.dataset.i18nAlt, el.getAttribute('alt') || ''));
  });
}

function detectInitialLanguage() {
  // 1. Check user preference previously stored in localStorage
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('sensuikan_user_lang');
    if (saved && getSupportedLanguages().includes(saved)) {
      return saved;
    }
  }
  // 2. Check browser / OS locale
  const browserLang = (typeof navigator !== 'undefined' ? (navigator.language || navigator.userLanguage || 'es') : 'es').toLowerCase();
  const browserMatch = getSupportedLanguages().find((language) => browserLang.startsWith(language));
  if (browserMatch) {
    return browserMatch;
  }
  return getSupportedLanguages().includes('en') ? 'en' : 'es';
}

